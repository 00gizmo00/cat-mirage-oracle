export function getTarotDetail(slug: string) {
  return tarotDetails.find((card) => card.slug === slug);
}

export function getRelatedTarotCards(currentSlug: string, limit = 3) {
  return tarotDetails
    .filter((card) => card.slug !== currentSlug)
    .slice(0, limit)
    .map((card) => ({ href: `/tarot/${card.slug}`, label: `${card.arcana} ${card.english}` }));
}
